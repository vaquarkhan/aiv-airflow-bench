#!/usr/bin/env python3
"""Collect one year of Airflow issues and dev-list mail for the AIV bench.

Window: 2025-10-22 .. 2026-10-22 (inclusive).

Scans every issue opened in that window on apache/airflow and every
dev@airflow.apache.org message in that window. Flags AI / LLM / slop
language. For each flagged issue, saves the full comment thread and the
linked pull-request patches so the gate can be run later.

This corpus is a signal set, not ground truth. expect_hard_fail is set
only when the same objective patch markers the bench already uses are
present.
"""

