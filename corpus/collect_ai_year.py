# Same hard markers as benchmarks/airflow/scripts/run-e2e-benchmark.py.
# Applied to reconstructed file text (diff prefixes removed), not the raw patch.
MARKER_RULES: list[tuple[str, re.Pattern[str]]] = [
    ("merge_conflict", re.compile(r"(?m)^(<<<<<<<|=======|>>>>>>>)\s")),
    ("ai_search_replace", re.compile(r"<<<<<<< SEARCH|>>>>>>> REPLACE")),
    (
        "ai_elision",
        re.compile(
            r"(?im)(\.\.\.\s*(existing|rest of|remaining)\b[^\n]*\b(code|implementation|unchanged)"
            r"|\b(rest|remainder) of (the )?(code|file|implementation)\b[^\n]*\b(unchanged|omitted)"
            r"|YOUR_CODE_HERE|INSERT_YOUR_CODE)"
        ),
    ),
    (
        "ai_assistant_chatter",
        re.compile(
            r"(?im)(as an ai language model|here'?s the (updated|complete|fixed|full) (code|implementation))"
        ),
    ),
    (
        "ai_attribution",
        re.compile(
            r"(?i)generated by (chatgpt|claude|copilot|gemini|ai)|as an ai language model"
        ),
    ),
]

FLAG_RULES: list[tuple[str, re.Pattern[str]]] = [
    (
        "ai_slop",
        re.compile(
            r"(?i)\b(?:ai[\s-]?slop|vibe[\s-]?cod(?:e|ing|ed)|slop|"
            r"hallucinat(?:e|ed|es|ion|ions)|ai[\s-]generated|"
            r"llm[\s-]generated|machine[\s-]generated)\b"
        ),
    ),
    (
        "llm_tool",
        re.compile(
            r"(?i)\b(?:llms?|large language models?|chat\s?gpt|gpt-?\d(?:\.\d)?o?|"
            r"openai|claude|anthropic|copilots?|geminis?|windsurf|tabnine|aider|"
            r"gen-?ai|codewhisperer|amazon q|cursor\.ai|cursor\.com|anysphere|"
            r"codex)\b"
            r"|(?-i:\b(?:Cursor|Devin|Grok)\b)"
        ),
    ),
    (
        "ai_disclosure",
        re.compile(
            r"(?i)\b(?:generated-by|generated by|ai-assisted|ai assisted|"
            r"written by (?:an? )?ai)\b"
        ),
    ),
    (
        "ai_mention",
        re.compile(r"(?i)\bartificial intelligence\b|(?<![A-Za-z0-9])AI(?![A-Za-z0-9])"),
    ),
]

PR_URL_RE = re.compile(r"https?://github\.com/apache/airflow/pull/(\d+)", re.I)
ISSUE_URL_RE = re.compile(r"https?://github\.com/apache/airflow/(?:issues|pull)/(\d+)", re.I)
HASH_RE = re.compile(r"(?<![A-Za-z0-9&/])#(\d{2,6})\b")
MSGID_RE = re.compile(r"<[^>]+>")
PATCH_CAP = 150_000
BODY_CAP = 200_000


def now_iso() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat()


def classify(text: str) -> dict[str, Any]:
    categories: list[str] = []
    terms: list[str] = []
    for name, pattern in FLAG_RULES:
        found = pattern.findall(text or "")
        if not found:
            continue
        categories.append(name)
        for hit in found:
            token = (hit if isinstance(hit, str) else hit[0]).strip().lower()
            if token and token not in terms:
                terms.append(token)
            if len(terms) >= 40:
                break
    return {
        "ai_related": bool(categories),
        "categories": categories,
        "matched_terms": terms,
    }


def scan_markers(text: str) -> list[str]:
    hits = []
    for name, pattern in MARKER_RULES:
        if text and pattern.search(text):
            hits.append(name)
    return hits


def content_from_patch(patch: str | None) -> str:
    if not patch:
        return ""
    lines: list[str] = []
    for line in patch.splitlines():
        if line.startswith("+++") or line.startswith("---") or line.startswith("@@"):
            continue
        if line.startswith("+"):
            lines.append(line[1:])
        elif line.startswith("-") or line.startswith("\\"):
            continue
        else:
            lines.append(line[1:] if line.startswith(" ") else line)
    return "\n".join(lines)


def gh_json(path: str, *, search: bool = False) -> Any:
    if search:
        time.sleep(2.5)
    proc = _gh(["gh", "api", path])
    if proc.returncode != 0 and _rate_limited(proc):
        print("  rate limit, waiting 60s", flush=True)
        time.sleep(60)
        proc = _gh(["gh", "api", path])
    if proc.returncode != 0:
        raise RuntimeError(f"gh api failed ({proc.returncode}): {(proc.stderr or proc.stdout)[:500]}")
    return json.loads(proc.stdout) if proc.stdout.strip() else None


def gh_graphql(query: str, variables: dict[str, Any] | None = None) -> Any:
    payload = json.dumps({"query": query, "variables": variables or {}})
    proc = _gh(["gh", "api", "graphql", "--input", "-"], input_text=payload)
    if proc.returncode != 0 and _rate_limited(proc):
        print("  graphql rate limit, waiting 60s", flush=True)
        time.sleep(60)
        proc = _gh(["gh", "api", "graphql", "--input", "-"], input_text=payload)
    if proc.returncode != 0:
        raise RuntimeError(f"graphql failed ({proc.returncode}): {(proc.stderr or proc.stdout)[:500]}")
    data = json.loads(proc.stdout)
    if data.get("errors"):
        raise RuntimeError(f"graphql errors: {json.dumps(data['errors'])[:500]}")
    return data["data"]


def _gh(cmd: list[str], input_text: str | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        cmd,
        input=input_text,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )


def _rate_limited(proc: subprocess.CompletedProcess[str]) -> bool:
    err = ((proc.stderr or "") + (proc.stdout or "")).lower()
    return "rate limit" in err or "http 403" in err or "http 429" in err


def month_ranges() -> list[tuple[dt.date, dt.date]]:
    ranges: list[tuple[dt.date, dt.date]] = []
    cursor = WINDOW_START.date()
    last = dt.date(2026, 10, 22)
    while cursor <= last:
        if cursor.month == 12:
            next_month = dt.date(cursor.year + 1, 1, 1)
        else:
            next_month = dt.date(cursor.year, cursor.month + 1, 1)
        end = min(last, next_month - dt.timedelta(days=1))
        ranges.append((cursor, end))
        cursor = end + dt.timedelta(days=1)
    return ranges


def gh_search(query: str, page: int) -> dict[str, Any]:
    """Search via form fields. A query-string page= parameter is ignored by gh."""
    time.sleep(2.5)
    cmd = [
        "gh", "api", "-X", "GET", "search/issues",
        "-f", f"q={query}",
        "-F", "per_page=100",
        "-F", f"page={page}",
        "-F", "sort=created",
        "-f", "order=asc",
    ]
    proc = _gh(cmd)
    if proc.returncode != 0 and _rate_limited(proc):
        print("  rate limit, waiting 60s", flush=True)
        time.sleep(60)
        proc = _gh(cmd)
    if proc.returncode != 0:
        raise RuntimeError(f"gh search failed ({proc.returncode}): {(proc.stderr or proc.stdout)[:500]}")
    return json.loads(proc.stdout) if proc.stdout.strip() else {}


def search_issues(start: dt.date, end: dt.date, depth: int = 0) -> list[dict[str, Any]]:
    query = f"repo:{REPO} is:issue created:{start.isoformat()}..{end.isoformat()}"
    print(f"search {start}..{end}", flush=True)
    first = gh_search(query, 1)
    total = int(first.get("total_count") or 0)
    span = (end - start).days
    # Search page 2 often comes back empty, and a whole month can report 0.
    # Split until each slice fits in one page. Retry a single empty day once.
    if span >= 1 and depth < 12 and (total == 0 or total > 100):
        print(f"  total {total}, splitting", flush=True)
        mid = start + dt.timedelta(days=span // 2)
        right = mid + dt.timedelta(days=1)
        return search_issues(start, mid, depth + 1) + search_issues(right, end, depth + 1)
    if total == 0 and span == 0:
        print("  total 0, fetching once more", flush=True)
        first = gh_search(query, 1)
        total = int(first.get("total_count") or 0)
    print(f"  total {total}", flush=True)
    items = list(first.get("items") or [])
    page = 2
    while len(items) < total and page <= 10:
        batch = gh_search(query, page).get("items") or []
        if not batch:
            break
        items.extend(batch)
        if len(batch) < 100:
            break
        page += 1
    if len(items) < total:
        print(f"  warning: collected {len(items)} of {total} for {start}..{end}", flush=True)
    return items


def slim_issue(item: dict[str, Any]) -> dict[str, Any]:
    body = item.get("body") or ""
    flag = classify(f"{item.get('title') or ''}\n{body}")
    user = item.get("user") or {}
    return {
        "number": item["number"],
        "url": item.get("html_url"),
        "title": item.get("title") or "",
        "state": item.get("state"),
        "state_reason": item.get("state_reason"),
        "created_at": item.get("created_at"),
        "updated_at": item.get("updated_at"),
        "closed_at": item.get("closed_at"),
        "user": user.get("login"),
        "author_association": item.get("author_association"),
        "labels": [l.get("name") for l in (item.get("labels") or []) if l.get("name")],
        "comments": item.get("comments"),
        "body": body,
        "flag": flag,
    }


def collect_issue_index() -> list[dict[str, Any]]:
    if ISSUES_PATH.is_file() and ISSUES_PATH.stat().st_size > 0:
        rows = [json.loads(line) for line in ISSUES_PATH.read_text(encoding="utf-8").splitlines() if line.strip()]
        if len(rows) >= 2200:
            print(f"reusing issue index ({len(rows)} rows)", flush=True)
            return rows
        print(f"ignoring short issue index ({len(rows)} rows)", flush=True)
    ROOT.mkdir(parents=True, exist_ok=True)
    seen: dict[int, dict[str, Any]] = {}
    for start, end in month_ranges():
        for item in search_issues(start, end):
            seen[item["number"]] = slim_issue(item)
    rows = [seen[n] for n in sorted(seen)]
    with ISSUES_PATH.open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"wrote {len(rows)} issues", flush=True)
    if len(rows) < 2100:
        raise RuntimeError(f"issue index is short ({len(rows)}); expected about 2431")
    return rows


COMMENT_QUERY = """
query {
  repository(owner: "apache", name: "airflow") {
    %ALIASES%
  }
}
""".strip()

ISSUE_FIELDS = """
number title body state createdAt updatedAt closedAt url
author { login }
authorAssociation
labels(first: 20) { nodes { name } }
comments(first: 100) {
  pageInfo { hasNextPage endCursor }
  nodes { author { login } createdAt body url }
}
""".strip()


def fetch_issue_threads(numbers: list[int]) -> dict[int, dict[str, Any]]:
    found: dict[int, dict[str, Any]] = {}
    for offset in range(0, len(numbers), 6):
        chunk = numbers[offset : offset + 6]
        aliases = "\n".join(
            f"i{n}: issue(number: {n}) {{ {ISSUE_FIELDS} }}" for n in chunk
        )
        query = COMMENT_QUERY.replace("%ALIASES%", aliases)
        print(f"  comments {chunk[0]}..{chunk[-1]} ({offset + len(chunk)}/{len(numbers)})", flush=True)
        data = gh_graphql(query)["repository"]
        for n in chunk:
            node = data.get(f"i{n}")
            if not node:
                continue
            comments = list((node.get("comments") or {}).get("nodes") or [])
            page = (node.get("comments") or {}).get("pageInfo") or {}
            cursor = page.get("endCursor")
            pages = 1
            while page.get("hasNextPage") and cursor and pages < 3:
                more = gh_graphql(
                    """
                    query($n: Int!, $after: String!) {
                      repository(owner: "apache", name: "airflow") {
                        issue(number: $n) {
                          comments(first: 100, after: $after) {
                            pageInfo { hasNextPage endCursor }
                            nodes { author { login } createdAt body url }
                          }
                        }
                      }
                    }
                    """,
                    {"n": n, "after": cursor},
                )["repository"]["issue"]
                block = (more or {}).get("comments") or {}
                comments.extend(block.get("nodes") or [])
                page = block.get("pageInfo") or {}
                cursor = page.get("endCursor")
                pages += 1
            node = dict(node)
            node["_comments"] = comments
            found[n] = node
        time.sleep(0.3)
    return found


def refs_from_text(text: str) -> tuple[list[int], list[int]]:
    prs = [int(n) for n in PR_URL_RE.findall(text or "")]
    any_nums = [int(n) for n in ISSUE_URL_RE.findall(text or "")]
    hashes = [int(n) for n in HASH_RE.findall(text or "")]
    ordered_prs: list[int] = []
    for n in prs:
        if n not in ordered_prs:
            ordered_prs.append(n)
    maybe: list[int] = []
    for n in any_nums + hashes:
        if n not in ordered_prs and n not in maybe:
            maybe.append(n)
    return ordered_prs[:8], maybe[:12]


KIND_CACHE: dict[int, str] = {}


def classify_numbers(numbers: list[int]) -> dict[int, str]:
    """Return number -> 'pr' | 'issue' | 'missing'.

    GraphQL rejects a mixed issue/pullRequest selection, so this uses REST.
    """
    kinds: dict[int, str] = {}
    for n in numbers:
        cached = KIND_CACHE.get(n)
        if cached:
            kinds[n] = cached
            continue
        proc = _gh(["gh", "api", f"repos/{REPO}/issues/{n}"])
        if proc.returncode != 0 and _rate_limited(proc):
            time.sleep(60)
            proc = _gh(["gh", "api", f"repos/{REPO}/issues/{n}"])
        if proc.returncode != 0:
            kind = "missing"
        else:
            data = json.loads(proc.stdout or "{}")
            kind = "pr" if isinstance(data, dict) and data.get("pull_request") else "issue"
        KIND_CACHE[n] = kind
        kinds[n] = kind
        time.sleep(0.1)
    return kinds


def fetch_pr(number: int) -> dict[str, Any]:
    dest = PR_DIR / f"{number}.json"
    if dest.is_file():
        return json.loads(dest.read_text(encoding="utf-8"))
    print(f"    pr #{number}", flush=True)
    pr = gh_json(f"repos/{REPO}/pulls/{number}")
    files: list[dict[str, Any]] = []
    page = 1
    truncated_files = False
    while page <= 3:
        batch = gh_json(
            f"repos/{REPO}/pulls/{number}/files?"
            + urllib.parse.urlencode({"per_page": "100", "page": str(page)})
        ) or []
        for f in batch:
            patch = f.get("patch") or ""
            truncated = False
            if len(patch) > PATCH_CAP:
                patch = patch[:PATCH_CAP]
                truncated = True
            files.append(
                {
                    "filename": f.get("filename"),
                    "status": f.get("status"),
                    "additions": f.get("additions"),
                    "deletions": f.get("deletions"),
                    "changes": f.get("changes"),
                    "patch": patch or None,
                    "patch_truncated": truncated,
                    "patch_omitted": f.get("patch") is None and f.get("status") != "removed",
                }
            )
        if len(batch) < 100:
            break
        if page == 3 and len(batch) == 100:
            truncated_files = True
        page += 1
    reconstructed = "\n".join(content_from_patch(f.get("patch")) for f in files)
    record = {
        "number": pr["number"],
        "url": pr.get("html_url"),
        "title": pr.get("title"),
        "state": pr.get("state"),
        "merged": bool(pr.get("merged")),
        "draft": bool(pr.get("draft")),
        "user": (pr.get("user") or {}).get("login"),
        "created_at": pr.get("created_at"),
        "closed_at": pr.get("closed_at"),
        "merged_at": pr.get("merged_at"),
        "base_sha": (pr.get("base") or {}).get("sha"),
        "head_sha": (pr.get("head") or {}).get("sha"),
        "additions": pr.get("additions"),
        "deletions": pr.get("deletions"),
        "changed_files": pr.get("changed_files"),
        "body": (pr.get("body") or "")[:BODY_CAP],
        "files_truncated": truncated_files,
        "files": files,
        "markers_in_patch": scan_markers(reconstructed),
        "flag": classify(f"{pr.get('title') or ''}\n{pr.get('body') or ''}"),
    }
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(record, ensure_ascii=False), encoding="utf-8")
    return record


def collect_issue_e2e(rows: list[dict[str, Any]]) -> None:
    ISSUE_DIR.mkdir(parents=True, exist_ok=True)
    flagged = [r for r in rows if r["flag"]["ai_related"]]
    pending = [r["number"] for r in flagged if not (ISSUE_DIR / f"{r['number']}.json").is_file()]
    print(f"flagged issues {len(flagged)}, pending e2e {len(pending)}", flush=True)
    if not pending:
        return
    threads = fetch_issue_threads(pending)
    by_num = {r["number"]: r for r in rows}
    for n in pending:
        base = by_num[n]
        node = threads.get(n)
        comments = []
        body = base["body"]
        title = base["title"]
        if not node:
            page = 1
            while page <= 3:
                batch = gh_json(
                    f"repos/{REPO}/issues/{n}/comments?"
                    + urllib.parse.urlencode({"per_page": "100", "page": str(page)})
                ) or []
                for c in batch:
                    comments.append(
                        {
                            "user": (c.get("user") or {}).get("login"),
                            "created_at": c.get("created_at"),
                            "url": c.get("html_url"),
                            "body": (c.get("body") or "")[:BODY_CAP],
                        }
                    )
                if len(batch) < 100:
                    break
                page += 1
        if node:
            body = node.get("body") or body
            title = node.get("title") or title
            for c in node.get("_comments") or []:
                if not c:
                    continue
                comments.append(
                    {
                        "user": (c.get("author") or {}).get("login"),
                        "created_at": c.get("createdAt"),
                        "url": c.get("url"),
                        "body": (c.get("body") or "")[:BODY_CAP],
                    }
                )
        blob = "\n".join([title, body, *[c["body"] for c in comments]])
        flag = classify(blob)
        pr_nums, maybe = refs_from_text(blob)
        kinds = classify_numbers(maybe) if maybe else {}
        linked_issues = []
        for num, kind in kinds.items():
            if kind == "pr" and num not in pr_nums:
                pr_nums.append(num)
            elif kind == "issue" and num != n:
                linked_issues.append(num)
        pr_nums = pr_nums[:8]
        pr_summaries = []
        markers: list[str] = []
        for prn in pr_nums:
            try:
                pr = fetch_pr(prn)
            except Exception as exc:  # noqa: BLE001
                pr_summaries.append({"number": prn, "error": str(exc)[:300]})
                continue
            markers.extend(m for m in pr["markers_in_patch"] if m not in markers)
            pr_summaries.append(
                {
                    "number": pr["number"],
                    "url": pr["url"],
                    "title": pr["title"],
                    "state": pr["state"],
                    "merged": pr["merged"],
                    "additions": pr["additions"],
                    "deletions": pr["deletions"],
                    "changed_files": pr["changed_files"],
                    "head_sha": pr["head_sha"],
                    "markers_in_patch": pr["markers_in_patch"],
                    "flag": pr["flag"],
                    "patch_file": f"prs/{prn}.json",
                }
            )
        record = {
            "schema_version": 1,
            "source": "github_issue",
            "window": WINDOW_LABEL,
            "collected_at": now_iso(),
            "issue": {
                "number": n,
                "url": base["url"],
                "title": title,
                "state": base["state"],
                "state_reason": base["state_reason"],
                "created_at": base["created_at"],
                "updated_at": base["updated_at"],
                "closed_at": base["closed_at"],
                "user": base["user"],
                "author_association": base["author_association"],
                "labels": base["labels"],
                "body": body[:BODY_CAP],
            },
            "flag": flag,
            "comments": comments,
            "linked_issues": linked_issues,
            "linked_prs": pr_summaries,
            "markers_in_patch": markers,
            "aiv": {
                "runnable": bool(pr_nums),
                "repo": REPO,
                "prs": pr_nums,
                "expect_hard_fail": bool(markers),
                "reason": (
                    "Objective patch markers present."
                    if markers
                    else (
                        "AI-related discussion with linked PR patches."
                        if pr_nums
                        else "AI-related discussion without a linked Airflow PR."
                    )
                ),
            },
        }
        (ISSUE_DIR / f"{n}.json").write_text(
            json.dumps(record, ensure_ascii=False), encoding="utf-8"
        )


def months_in_window() -> list[str]:
    labels = []
    cursor = WINDOW_START.date().replace(day=1)
    last = dt.date(2026, 10, 1)
    while cursor <= last:
        labels.append(f"{cursor.year:04d}-{cursor.month:02d}")
        if cursor.month == 12:
            cursor = dt.date(cursor.year + 1, 1, 1)
        else:
            cursor = dt.date(cursor.year, cursor.month + 1, 1)
    return labels


def download_mbox(ym: str) -> Path:
    MBOX_DIR.mkdir(parents=True, exist_ok=True)
    dest = MBOX_DIR / f"{ym}.mbox"
    if dest.is_file() and dest.stat().st_size > 0:
        print(f"reusing mbox {ym} ({dest.stat().st_size} bytes)", flush=True)
        return dest
    url = (
        "https://lists.apache.org/api/mbox.json?"
        + urllib.parse.urlencode(
            {
                "list": "dev",
                "domain": "airflow.apache.org",
                "social": "yes",
                "d": ym,
            }
        )
    )
    print(f"download mbox {ym}", flush=True)
    req = urllib.request.Request(url, headers={"User-Agent": "aiv-airflow-bench-corpus"})
    with urllib.request.urlopen(req, timeout=180) as resp, dest.open("wb") as fh:
        total = 0
        while True:
            chunk = resp.read(1024 * 256)
            if not chunk:
                break
            fh.write(chunk)
            total += len(chunk)
            if total > 80 * 1024 * 1024:
                raise RuntimeError(f"mbox {ym} exceeded 80MB")
    print(f"  {dest.stat().st_size} bytes", flush=True)
    return dest


def message_text(msg: email.message.Message) -> str:
    if msg.is_multipart():
        plain: list[str] = []
        html_parts: list[str] = []
        for part in msg.walk():
            disp = str(part.get("Content-Disposition") or "")
            if "attachment" in disp.lower():
                continue
            ctype = part.get_content_type()
            if ctype not in ("text/plain", "text/html"):
                continue
            payload = part.get_payload(decode=True)
            if not payload:
                continue
            charset = part.get_content_charset() or "utf-8"
            text = payload.decode(charset, errors="replace")
            if ctype == "text/plain":
                plain.append(text)
            else:
                html_parts.append(text)
        if plain:
            return "\n".join(plain)
        raw = "\n".join(html_parts)
        raw = re.sub(r"(?is)<(script|style).*?>.*?</\1>", " ", raw)
        raw = re.sub(r"(?s)<[^>]+>", " ", raw)
        return re.sub(r"[ \t]+\n", "\n", raw)
    payload = msg.get_payload(decode=True)
    if not payload:
        return str(msg.get_payload() or "")
    charset = msg.get_content_charset() or "utf-8"
    return payload.decode(charset, errors="replace")


def as_utc(value: dt.datetime) -> dt.datetime:
    if value.tzinfo is None:
        return value.replace(tzinfo=dt.timezone.utc)
    return value.astimezone(dt.timezone.utc)


def header_ids(value: str | None) -> list[str]:
    return MSGID_RE.findall(value or "")


def collect_mail() -> list[dict[str, Any]]:
    if MAIL_PATH.is_file() and MAIL_PATH.stat().st_size > 0 and any(THREAD_DIR.glob("*.json")):
        rows = [json.loads(line) for line in MAIL_PATH.read_text(encoding="utf-8").splitlines() if line.strip()]
        print(f"reusing mail index ({len(rows)} messages)", flush=True)
        return rows
    messages: list[dict[str, Any]] = []
    seen_ids: set[str] = set()
    for ym in months_in_window():
        path = download_mbox(ym)
        box = mailbox.mbox(path)
        try:
            for msg in box:
                mid = (msg.get("Message-ID") or "").strip()
                if mid and mid in seen_ids:
                    continue
                raw_date = msg.get("Date")
                try:
                    when = as_utc(parsedate_to_datetime(raw_date)) if raw_date else None
                except (TypeError, ValueError, IndexError):
                    when = None
                if when is None or when < WINDOW_START or when >= WINDOW_END:
                    continue
                if mid:
                    seen_ids.add(mid)
                body = message_text(msg)[:BODY_CAP]
                subject = str(msg.get("Subject") or "")
                flag = classify(f"{subject}\n{body}")
                refs = header_ids(msg.get("References"))
                irt = header_ids(msg.get("In-Reply-To"))
                root = refs[0] if refs else (irt[0] if irt else mid)
                messages.append(
                    {
                        "message_id": mid,
                        "root_id": root,
                        "date": when.isoformat(),
                        "from": str(msg.get("From") or ""),
                        "subject": subject,
                        "in_reply_to": irt[0] if irt else None,
                        "list": "dev@airflow.apache.org",
                        "month": ym,
                        "body": body,
                        "flag": flag,
                    }
                )
        finally:
            box.close()
        path.unlink(missing_ok=True)
        print(f"  messages kept so far {len(messages)}", flush=True)
    MAIL_PATH.parent.mkdir(parents=True, exist_ok=True)
    with MAIL_PATH.open("w", encoding="utf-8") as fh:
        for row in messages:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    write_mail_threads(messages)
    return messages


def write_mail_threads(messages: list[dict[str, Any]]) -> None:
    THREAD_DIR.mkdir(parents=True, exist_ok=True)
    groups: dict[str, list[dict[str, Any]]] = {}
    for row in messages:
        if row["flag"]["ai_related"]:
            groups.setdefault(row["root_id"] or row["message_id"] or row["date"], []).append(row)
    # Pull sibling messages from the same root even when a reply itself is unflagged.
    flagged_roots = set(groups)
    groups = {root: [] for root in flagged_roots}
    for row in messages:
        root = row["root_id"] or row["message_id"]
        if root in groups:
            groups[root].append(row)
    for root, rows in groups.items():
        rows.sort(key=lambda r: r["date"])
        categories: list[str] = []
        terms: list[str] = []
        for row in rows:
            for cat in row["flag"]["categories"]:
                if cat not in categories:
                    categories.append(cat)
            for term in row["flag"]["matched_terms"]:
                if term not in terms:
                    terms.append(term)
        digest = hashlib.sha1((root or rows[0]["subject"]).encode("utf-8", errors="replace")).hexdigest()[:16]
        record = {
            "schema_version": 1,
            "source": "airflow_dev_list",
            "window": WINDOW_LABEL,
            "list_url": LIST_URL,
            "root_id": root,
            "subject": rows[0]["subject"],
            "flag": {
                "ai_related": True,
                "categories": categories,
                "matched_terms": terms[:40],
            },
            "messages": rows,
        }
        (THREAD_DIR / f"{digest}.json").write_text(
            json.dumps(record, ensure_ascii=False), encoding="utf-8"
        )
    print(f"mail threads {len(groups)}", flush=True)


def write_cases(rows: list[dict[str, Any]]) -> dict[str, Any]:
    pr_cases: dict[int, dict[str, Any]] = {}
    issue_cases = []
    for path in sorted(ISSUE_DIR.glob("*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        issue = rec["issue"]
        issue_cases.append(
            {
                "id": f"issue-{issue['number']}",
                "issue": issue["number"],
                "url": issue["url"],
                "title": issue["title"],
                "created_at": issue["created_at"],
                "state": issue["state"],
                "categories": rec["flag"]["categories"],
                "matched_terms": rec["flag"]["matched_terms"],
                "comment_count": len(rec["comments"]),
                "linked_prs": [p.get("number") for p in rec["linked_prs"] if p.get("number")],
                "markers_in_patch": rec["markers_in_patch"],
                "runnable": rec["aiv"]["runnable"],
            }
        )
        for pr in rec["linked_prs"]:
            if not pr.get("number") or pr.get("error"):
                continue
            slot = pr_cases.setdefault(
                pr["number"],
                {
                    "id": f"airflow-pr-{pr['number']}",
                    "source": "github",
                    "repo": REPO,
                    "pr": pr["number"],
                    "url": pr.get("url"),
                    "title": pr.get("title"),
                    "state": pr.get("state"),
                    "merged": pr.get("merged"),
                    "head_sha": pr.get("head_sha"),
                    "origin_issues": [],
                    "markers_in_patch": pr.get("markers_in_patch") or [],
                    "label": {
                        "class": "ai_signal_unlabeled",
                        "expect_hard_fail": False,
                        "notes": (
                            "Linked from an AI-flagged Airflow issue in "
                            f"{WINDOW_LABEL}. Not human ground truth."
                        ),
                    },
                },
            )
            if issue["number"] not in slot["origin_issues"]:
                slot["origin_issues"].append(issue["number"])
            for marker in pr.get("markers_in_patch") or []:
                if marker not in slot["markers_in_patch"]:
                    slot["markers_in_patch"].append(marker)
    for slot in pr_cases.values():
        if slot["markers_in_patch"]:
            slot["label"] = {
                "class": "objective_slop",
                "expect_hard_fail": True,
                "notes": (
                    "Patch text matched bench hard markers: "
                    + ", ".join(slot["markers_in_patch"])
                ),
            }
    cases = {
        "schema_version": 1,
        "generated_at": now_iso(),
        "window": WINDOW_LABEL,
        "repo": REPO,
        "note": (
            "Signal corpus for end-to-end AIV runs. AI flags are lexical. "
            "expect_hard_fail is true only when objective patch markers matched. "
            "Disclosure or the word AI is not a fail label."
        ),
        "issue_cases": issue_cases,
        "pr_cases": list(pr_cases.values()),
    }
    CASES_PATH.write_text(json.dumps(cases, ensure_ascii=False, indent=2), encoding="utf-8")
    return cases


def write_manifest(rows: list[dict[str, Any]], mail_rows: list[dict[str, Any]], cases: dict[str, Any]) -> None:
    def tally(flags: list[dict[str, Any]]) -> dict[str, int]:
        counts = {"ai_related": 0, "ai_slop": 0, "llm_tool": 0, "ai_disclosure": 0, "ai_mention": 0}
        for flag in flags:
            if flag.get("ai_related"):
                counts["ai_related"] += 1
            for cat in flag.get("categories") or []:
                counts[cat] = counts.get(cat, 0) + 1
        return counts

    thread_files = list(THREAD_DIR.glob("*.json")) if THREAD_DIR.is_dir() else []
    manifest = {
        "schema_version": 1,
        "generated_at": now_iso(),
        "window": WINDOW_LABEL,
        "sources": {
            "issues": f"https://github.com/{REPO}/issues",
            "dev_list": LIST_URL,
        },
        "lexicon": {
            "ai_slop": "slop, vibe coding, hallucination, ai-generated, llm-generated",
            "llm_tool": "LLM, ChatGPT, GPT-n, OpenAI, Claude, Copilot, Gemini, Codex, Cursor, Devin, Grok, Windsurf",
            "ai_disclosure": "generated-by, generated by, ai-assisted",
            "ai_mention": "standalone AI or artificial intelligence",
        },
        "not_claimed": [
            "A lexical AI flag is not proof of AI authorship.",
            "A lexical AI flag is not proof the change should fail the gate.",
            "Bare 'AI' includes product work (providers, features), not only slop.",
            "Search totals are not a measure of AI-slop volume.",
        ],
        "issues": {
            "scanned": len(rows),
            "by_category": tally([r["flag"] for r in rows]),
            "e2e_files": len(list(ISSUE_DIR.glob("*.json"))) if ISSUE_DIR.is_dir() else 0,
        },
        "pull_requests": {
            "linked_unique": len(cases.get("pr_cases") or []),
            "with_objective_markers": sum(
                1 for c in cases.get("pr_cases") or [] if c.get("markers_in_patch")
            ),
            "stored_patch_files": len(list(PR_DIR.glob("*.json"))) if PR_DIR.is_dir() else 0,
        },
        "mailing_list": {
            "messages_scanned": len(mail_rows),
            "by_category": tally([r["flag"] for r in mail_rows]),
            "threads": len(thread_files),
        },
        "artifacts": {
            "issues_index": "corpus/ai-year/issues-all.jsonl",
            "issue_e2e": "corpus/ai-year/issues/<number>.json",
            "pr_patches": "corpus/ai-year/prs/<number>.json",
            "mail_index": "corpus/ai-year/mail-index.jsonl",
            "mail_threads": "corpus/ai-year/mail-threads/<id>.json",
            "aiv_cases": "corpus/ai-year/aiv-cases.json",
        },
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    summary = {
        "schema_version": 1,
        "generated_at": manifest["generated_at"],
        "window": WINDOW_LABEL,
        "issues_scanned": manifest["issues"]["scanned"],
        "issues_by_category": manifest["issues"]["by_category"],
        "prs_linked": manifest["pull_requests"]["linked_unique"],
        "prs_with_objective_markers": manifest["pull_requests"]["with_objective_markers"],
        "mail_messages_scanned": manifest["mailing_list"]["messages_scanned"],
        "mail_by_category": manifest["mailing_list"]["by_category"],
        "mail_threads": manifest["mailing_list"]["threads"],
        "not_claimed": manifest["not_claimed"],
        "flagged_issues": cases.get("issue_cases") or [],
    }
    SUMMARY_PATH.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_PATH.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({k: manifest[k] for k in ("issues", "pull_requests", "mailing_list")}, indent=2), flush=True)


def main() -> int:
    ROOT.mkdir(parents=True, exist_ok=True)
    rows = collect_issue_index()
    collect_issue_e2e(rows)
    mail_rows = collect_mail()
    cases = write_cases(rows)
    write_manifest(rows, mail_rows, cases)
    return 0


