#!/usr/bin/env python3
"""Second, third, and fourth AIV benches: Flink, Kafka, and curl.

Window 2025-10-22..2026-10-22. Each quarter contributes a capped sample of
filled AI disclosures, slop-language discussions, merged controls, and any
patch that contains the bench hard markers. Apache dev-list threads for
Flink and Kafka are saved alongside the code.

curl is included because its maintainers shut the bug bounty in January 2026
after AI-generated reports overwhelmed the security team. That is public
reporting, not a claim that every curl PR is slop.
"""

from __future__ import annotations

import datetime as dt
import json
import subprocess
import time
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any

import re

BENCH = Path(__file__).resolve().parents[1]
CORPUS = Path(__file__).resolve().parent / "benchmarks"
WINDOW = "2025-10-22..2026-10-22"
START = dt.datetime(2025, 10, 22, tzinfo=dt.timezone.utc)
END = dt.datetime(2026, 10, 23, tzinfo=dt.timezone.utc)
PATCH_CAP = 100_000
MAX_ADDITIONS = 5000
MAX_FILES = 40

PROJECTS = [
    {
        "id": "flink",
        "bench": 2,
        "repo": "apache/flink",
        "list_domain": "flink.apache.org",
        "why": "Dev list discussed AI-assisted contributions, AGENTS.md, and a disclosure checkbox in 2026.",
    },
    {
        "id": "kafka",
        "bench": 3,
        "repo": "apache/kafka",
        "list_domain": "kafka.apache.org",
        "why": "Kafka dev list and pull requests are the third bench, parallel to Airflow and Flink.",
    },
    {
        "id": "curl",
        "bench": 4,
        "repo": "curl/curl",
        "list_domain": None,
        "why": "Maintainers ended the curl bug bounty on 31 Jan 2026 after AI-generated reports overwhelmed the security team.",
    },
]

MARKER_RULES = [
    ("merge_conflict", re.compile(r"(?m)^(<<<<<<<|=======|>>>>>>>)\s")),
    ("ai_search_replace", re.compile(r"<<<<<<< SEARCH|>>>>>>> REPLACE")),
    (
        "ai_elision",
        re.compile(
            r"(?im)(\.\.\.\s*(existing|rest of|remaining)\b[^\n]*\b(code|implementation|unchanged)"
            r"|\b(rest|remainder) of (the )?(code|file|implementation)\b[^\n]*\b(unchanged|omitted)"
            r"|YOUR_CODE_HERE|INSERT_YOUR_CODE)"
        ),
    ),
    (
        "ai_assistant_chatter",
        re.compile(r"(?im)(as an ai language model|here'?s the (updated|complete|fixed|full) (code|implementation))"),
    ),
    (
        "ai_attribution",
        re.compile(r"(?i)generated by (chatgpt|claude|copilot|gemini|ai)|as an ai language model"),
    ),
]
SLOP_RE = re.compile(
    r"(?i)\b(?:ai[\s-]?slop|vibe[\s-]?cod(?:e|ing|ed)|slop|hallucinat(?:e|ed|es|ion|ions)|"
    r"ai[\s-]generated|llm[\s-]generated|machine[\s-]generated)\b"
)
TOOL_RE = re.compile(
    r"(?i)\b(?:llms?|chat\s?gpt|gpt-?\d|openai|claude|anthropic|copilots?|gemini|codex|cursor\.ai)\b|\bCursor\b"
)
GENERATED_BY = re.compile(r"(?im)^[ \t>*-]*Generated-by:\s*(.+)$")
CHECKBOX = re.compile(
    r"(?im)^\s*(?:[-*]\s*)?\[\s*[xX]\s*\].{0,160}(chatgpt|claude|codex|copilot|gemini|generative ai|ai[\s-]assisted)"
)
MAIL_QUERIES = [
    "slop", "LLM", "Claude", "ChatGPT", "Copilot", "Codex",
    "generative", "AI-assisted", "AGENTS.md", "hallucin", "disclosure",
]


def now_iso() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat()


def quarters() -> list[tuple[dt.date, dt.date]]:
    cuts = [
        dt.date(2025, 10, 22), dt.date(2026, 1, 22), dt.date(2026, 4, 22),
        dt.date(2026, 7, 22), dt.date(2026, 10, 22),
    ]
    return list(zip(cuts, cuts[1:]))


def _gh(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")


def _limited(proc: subprocess.CompletedProcess[str]) -> bool:
    blob = ((proc.stderr or "") + (proc.stdout or "")).lower()
    return "rate limit" in blob or "http 403" in blob or "http 429" in blob


def gh_json(path: str) -> Any:
    proc = _gh(["gh", "api", path])
    if proc.returncode != 0 and _limited(proc):
        print("  rate limit, waiting 60s", flush=True)
        time.sleep(60)
        proc = _gh(["gh", "api", path])
    if proc.returncode != 0:
        raise RuntimeError((proc.stderr or proc.stdout)[:400])
    return json.loads(proc.stdout) if proc.stdout.strip() else None


def gh_search(query: str, per_page: int) -> dict[str, Any]:
    time.sleep(2.4)
    cmd = [
        "gh", "api", "-X", "GET", "search/issues",
        "-f", f"q={query}",
        "-F", f"per_page={per_page}",
        "-F", "page=1",
        "-F", "sort=created",
        "-f", "order=desc",
    ]
    proc = _gh(cmd)
    if proc.returncode != 0 and _limited(proc):
        time.sleep(60)
        proc = _gh(cmd)
    if proc.returncode != 0:
        raise RuntimeError(f"search failed: {(proc.stderr or proc.stdout)[:300]}")
    return json.loads(proc.stdout) if proc.stdout.strip() else {}


def search_range(repo: str, start: dt.date, end: dt.date, extra: str, per_page: int, depth: int = 0) -> tuple[int, list[dict[str, Any]]]:
    query = f"repo:{repo} created:{start.isoformat()}..{end.isoformat()} {extra}".strip()
    print(f"  {repo} {start}..{end} {extra}", flush=True)
    data = gh_search(query, per_page)
    total = int(data.get("total_count") or 0)
    items = list(data.get("items") or [])
    print(f"    total {total} page {len(items)}", flush=True)
    if total == 0 and (end - start).days >= 14 and depth < 3:
        mid = start + dt.timedelta(days=(end - start).days // 2)
        t1, i1 = search_range(repo, start, mid, extra, per_page, depth + 1)
        t2, i2 = search_range(repo, mid + dt.timedelta(days=1), end, extra, per_page, depth + 1)
        seen: dict[int, dict[str, Any]] = {}
        for item in i1 + i2:
            seen[item["number"]] = item
        return t1 + t2, list(seen.values())
    return total, items


def disclosure(body: str) -> dict[str, Any]:
    signals: list[str] = []
    tool = None
    if CHECKBOX.search(body or ""):
        signals.append("checkbox_yes")
    match = GENERATED_BY.search(body or "")
    val = (match.group(1) if match else "").strip()
    placeholder = (not val) or val.startswith("[") or "tool name" in val.lower() or val.lower().startswith("following")
    if val and not placeholder:
        signals.append("generated_by_filled")
        tool = val.split(" following ", 1)[0].strip()[:80]
    return {"signals": signals, "disclosed": bool(signals), "generated_by": tool}


def text_flags(text: str) -> dict[str, Any]:
    slop = sorted({m.group(0).lower() for m in SLOP_RE.finditer(text or "")})
    tools = sorted({m.group(0).lower() for m in TOOL_RE.finditer(text or "")})
    return {"slop_terms": slop[:20], "tool_terms": tools[:20], "slop": bool(slop), "tool": bool(tools)}


def content_from_patch(patch: str | None) -> str:
    if not patch:
        return ""
    lines = []
    for line in patch.splitlines():
        if line.startswith(("+++", "---", "@@", "-", "\\")):
            continue
        lines.append(line[1:] if line[:1] in "+ " else line)
    return "\n".join(lines)


def scan_markers(text: str) -> list[str]:
    return [name for name, pattern in MARKER_RULES if text and pattern.search(text)]


def fetch_pr(repo: str, number: int, dest: Path) -> dict[str, Any]:
    if dest.is_file():
        return json.loads(dest.read_text(encoding="utf-8"))
    pr = gh_json(f"repos/{repo}/pulls/{number}")
    additions = int(pr.get("additions") or 0)
    changed = int(pr.get("changed_files") or 0)
    too_big = additions > MAX_ADDITIONS or changed > MAX_FILES
    files: list[dict[str, Any]] = []
    markers: list[str] = []
    if not too_big:
        batch = gh_json(
            f"repos/{repo}/pulls/{number}/files?" + urllib.parse.urlencode({"per_page": "100", "page": "1"})
        ) or []
        for f in batch:
            patch = f.get("patch") or ""
            truncated = len(patch) > PATCH_CAP
            files.append({
                "filename": f.get("filename"),
                "status": f.get("status"),
                "additions": f.get("additions"),
                "deletions": f.get("deletions"),
                "patch": (patch[:PATCH_CAP] if patch else None),
                "patch_truncated": truncated,
                "patch_omitted": f.get("patch") is None and f.get("status") != "removed",
            })
        markers = scan_markers("\n".join(content_from_patch(f.get("patch")) for f in files))
    body = pr.get("body") or ""
    record = {
        "number": pr["number"],
        "url": pr.get("html_url"),
        "title": pr.get("title"),
        "state": pr.get("state"),
        "merged": bool(pr.get("merged")),
        "user": (pr.get("user") or {}).get("login"),
        "created_at": pr.get("created_at"),
        "closed_at": pr.get("closed_at"),
        "merged_at": pr.get("merged_at"),
        "head_sha": (pr.get("head") or {}).get("sha"),
        "base_sha": (pr.get("base") or {}).get("sha"),
        "additions": additions,
        "deletions": pr.get("deletions"),
        "changed_files": changed,
        "too_big": too_big,
        "body": body[:60_000],
        "disclosure": disclosure(body),
        "flags": text_flags(f"{pr.get('title') or ''}\n{body}"),
        "markers_in_patch": markers,
        "files": files,
    }
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(record, ensure_ascii=False), encoding="utf-8")
    return record


def classify(pr: dict[str, Any] | None, text: str, cohort: str, merged: bool) -> dict[str, Any]:
    markers = (pr or {}).get("markers_in_patch") or []
    flags = text_flags(text)
    disc = (pr or {}).get("disclosure") or disclosure(text)
    if markers:
        return {
            "class": "objective_slop",
            "expect_hard_fail": True,
            "rationale": "Patch contains bench hard markers: " + ", ".join(markers),
        }
    if flags["slop"] and cohort != "merged_control":
        return {
            "class": "ai_slop_discussion",
            "expect_hard_fail": False,
            "rationale": "Slop, hallucination, or AI-generated language in the text. Not a patch-marker fail.",
        }
    if disc.get("disclosed") and cohort != "merged_control":
        return {
            "class": "ai_disclosed",
            "expect_hard_fail": False,
            "rationale": "Filled Generated-by or AI checkbox. Disclosure is not a fail label.",
        }
    if cohort == "merged_control" and merged and not disc.get("disclosed") and not flags["slop"]:
        return {
            "class": "merged_control",
            "expect_hard_fail": False,
            "rationale": "Merged, no filled disclosure, no slop language, no hard markers.",
        }
    if flags["tool"]:
        return {
            "class": "ai_tool_mention",
            "expect_hard_fail": False,
            "rationale": "Names an LLM tool. Not labeled slop.",
        }
    return {
        "class": "other",
        "expect_hard_fail": False,
        "rationale": "Kept from a search page but no slop, disclosure, or marker signal.",
    }


def consider(repo: str, item: dict[str, Any], cohort: str, seen: dict[int, dict[str, Any]], pr_dir: Path, quota_left: int) -> bool:
    if quota_left <= 0:
        return False
    number = int(item["number"])
    if number in seen:
        return False
    is_pr = bool(item.get("pull_request"))
    body = item.get("body") or ""
    title = item.get("title") or ""
    if cohort == "merged_control":
        if disclosure(body)["disclosed"] or text_flags(f"{title}\n{body}")["slop"]:
            return False
    pr = None
    if is_pr:
        try:
            pr = fetch_pr(repo, number, pr_dir / f"{number}.json")
        except Exception as exc:  # noqa: BLE001
            print(f"    skip {repo}#{number}: {exc}", flush=True)
            return False
        if pr.get("too_big"):
            print(f"    skip {repo}#{number} size +{pr['additions']}", flush=True)
            return False
        body = pr["body"]
        title = pr["title"] or title
    label = classify(pr, f"{title}\n{body}", cohort, bool((pr or {}).get("merged") or cohort == "merged_control"))
    if cohort == "marker_search" and label["class"] != "objective_slop":
        return False
    if cohort == "slop_search" and label["class"] not in ("ai_slop_discussion", "objective_slop", "ai_disclosed", "ai_tool_mention"):
        return False
    if cohort == "disclosure_search" and label["class"] not in ("ai_disclosed", "objective_slop"):
        return False
    if label["class"] == "other":
        return False
    case = {
        "id": f"{repo.split('/')[-1]}-{number}",
        "source": "github",
        "repo": repo,
        "kind": "pull_request" if is_pr else "issue",
        "number": number,
        "url": (pr or {}).get("url") or item.get("html_url"),
        "title": title,
        "state": (pr or {}).get("state") or item.get("state"),
        "merged": bool((pr or {}).get("merged")),
        "created_at": (pr or {}).get("created_at") or item.get("created_at"),
        "user": (pr or {}).get("user") or (item.get("user") or {}).get("login"),
        "cohort": cohort,
        "runnable": bool(is_pr and pr and not pr.get("too_big")),
        "head_sha": (pr or {}).get("head_sha"),
        "additions": (pr or {}).get("additions"),
        "changed_files": (pr or {}).get("changed_files"),
        "disclosure": (pr or {}).get("disclosure") or disclosure(body),
        "flags": (pr or {}).get("flags") or text_flags(f"{title}\n{body}"),
        "markers_in_patch": (pr or {}).get("markers_in_patch") or [],
        "label": label,
        "body": body[:40_000],
        "patch_file": f"prs/{number}.json" if is_pr else None,
    }
    seen[number] = case
    print(f"    {repo}#{number} {label['class']}", flush=True)
    return True


def collect_github(project: dict[str, Any]) -> list[dict[str, Any]]:
    repo = project["repo"]
    root = CORPUS / project["id"]
    pr_dir = root / "prs"
    seen: dict[int, dict[str, Any]] = {}
    for start, end in quarters():
        for cohort, extra, cap in (
            ("disclosure_search", 'is:pr "Generated-by:"', 8),
            ("slop_search", 'slop OR "AI-generated" OR "AI generated" OR hallucinat OR "vibe coding" OR "LLM-generated"', 8),
            ("marker_search", 'is:pr "<<<<<<< SEARCH"', 4),
            ("merged_control", "is:pr is:merged", 6),
        ):
            _total, items = search_range(repo, start, end, extra, max(cap * 3, 12))
            kept = 0
            for item in items:
                if consider(repo, item, cohort, seen, pr_dir, cap - kept):
                    kept += 1
    return [seen[n] for n in sorted(seen)]


def http_json(url: str) -> Any:
    req = urllib.request.Request(url, headers={"User-Agent": "aiv-bench-corpus"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.loads(resp.read().decode("utf-8"))


def collect_mail(domain: str, dest: Path) -> list[dict[str, Any]]:
    threads: dict[str, dict[str, Any]] = {}
    for q in MAIL_QUERIES:
        url = "https://lists.apache.org/api/stream.json?" + urllib.parse.urlencode({
            "list": "dev", "domain": domain, "social": "yes", "q": q,
            "quant": "20", "page": "0",
        })
        try:
            data = http_json(url)
        except Exception as exc:  # noqa: BLE001
            print(f"  mail {domain} {q}: {exc}", flush=True)
            continue
        rows = data.get("rows") or []
        print(f"  mail {domain} {q}: {data.get('total')} threads, page {len(rows)}", flush=True)
        for row in rows:
            tid = row.get("tid")
            if not tid or tid in threads:
                continue
            epoch = int(row.get("epoch") or 0)
            last = int(row.get("last_epoch") or epoch)
            started = dt.datetime.fromtimestamp(epoch, dt.timezone.utc)
            ended = dt.datetime.fromtimestamp(last, dt.timezone.utc)
            if ended < START or started >= END:
                continue
            starter = row.get("starter") or {}
            blob = f"{row.get('subject') or ''}\n{starter.get('body') or ''}"
            flags = text_flags(blob)
            disc = disclosure(blob)
            if not (flags["slop"] or flags["tool"] or disc["disclosed"] or SLOP_RE.search(q) or TOOL_RE.search(q)):
                # The query itself is the reason the thread was retrieved.
                flags["tool"] = flags["tool"] or bool(TOOL_RE.search(q) or q.lower() in {"llm", "claude", "chatgpt", "copilot", "codex", "generative"})
            threads[tid] = {
                "tid": tid,
                "subject": row.get("subject"),
                "epoch": epoch,
                "last_epoch": last,
                "date": started.isoformat(),
                "last_date": ended.isoformat(),
                "replies": row.get("replies"),
                "list": f"dev@{domain}",
                "url": f"https://lists.apache.org/thread/{tid}",
                "query": q,
                "flags": flags,
                "disclosure": disc,
                "starter_excerpt": (starter.get("body") or "")[:1500],
            }
            if len(threads) >= 40:
                break
        if len(threads) >= 40:
            break
    dest.mkdir(parents=True, exist_ok=True)
    saved = list(threads.values())
    for row in saved:
        (dest / f"{row['tid']}.json").write_text(json.dumps(row, ensure_ascii=False, indent=2), encoding="utf-8")
    return saved


def write_project(project: dict[str, Any], cases: list[dict[str, Any]], mail: list[dict[str, Any]]) -> dict[str, Any]:
    root = CORPUS / project["id"]
    root.mkdir(parents=True, exist_ok=True)
    by_class: dict[str, int] = {}
    for case in cases:
        by_class[case["label"]["class"]] = by_class.get(case["label"]["class"], 0) + 1
    mail_slop = sum(1 for row in mail if row["flags"].get("slop"))
    doc = {
        "schema_version": 1,
        "bench": project["bench"],
        "project": project["id"],
        "repo": project["repo"],
        "window": WINDOW,
        "generated_at": now_iso(),
        "why": project["why"],
        "sampling": "Up to a fixed number of latest matches per quarter. Not a census. A zero-hit quarter is split before it is trusted.",
        "not_claimed": [
            "A tool mention or filled Generated-by line is not proof the change should fail.",
            "Slop language in discussion is not proof the attached patch is slop.",
            "Search totals are not the percent of the project that is AI-authored.",
        ],
        "stats": {
            "cases": len(cases),
            "runnable_prs": sum(1 for c in cases if c["runnable"]),
            "by_class": by_class,
            "objective_slop": by_class.get("objective_slop", 0),
            "ai_slop_discussion": by_class.get("ai_slop_discussion", 0),
            "ai_disclosed": by_class.get("ai_disclosed", 0),
            "merged_control": by_class.get("merged_control", 0),
            "mail_threads": len(mail),
            "mail_slop_language": mail_slop,
        },
        "cases": cases,
        "mail_threads": [
            {
                "tid": row["tid"],
                "subject": row["subject"],
                "date": row["date"],
                "url": row["url"],
                "replies": row["replies"],
                "slop_terms": row["flags"].get("slop_terms"),
                "tool_terms": row["flags"].get("tool_terms"),
            }
            for row in mail
        ],
    }
    (root / "cases.json").write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
    summary = {
        "schema_version": 1,
        "bench": project["bench"],
        "project": project["id"],
        "repo": project["repo"],
        "window": WINDOW,
        "generated_at": doc["generated_at"],
        "why": project["why"],
        "stats": doc["stats"],
        "not_claimed": doc["not_claimed"],
        "cases": [
            {
                "number": c["number"],
                "kind": c["kind"],
                "url": c["url"],
                "title": c["title"],
                "label": c["label"]["class"],
                "expect_hard_fail": c["label"]["expect_hard_fail"],
                "merged": c["merged"],
                "markers_in_patch": c["markers_in_patch"],
                "generated_by": (c.get("disclosure") or {}).get("generated_by"),
                "slop_terms": (c.get("flags") or {}).get("slop_terms"),
            }
            for c in cases
        ],
        "mail_threads": doc["mail_threads"],
    }
    out = BENCH / "docs" / "data" / f"{project['id']}-bench-latest.json"
    out.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    (root / "manifest.json").write_text(json.dumps({
        "bench": project["bench"],
        "repo": project["repo"],
        "generated_at": doc["generated_at"],
        "stats": doc["stats"],
        "why": project["why"],
    }, indent=2), encoding="utf-8")
    print(project["id"], json.dumps(doc["stats"]), flush=True)
    return doc["stats"]


def main() -> int:
    index = []
    for project in PROJECTS:
        print(f"=== bench {project['bench']} {project['repo']} ===", flush=True)
        cases = collect_github(project)
        mail: list[dict[str, Any]] = []
        if project["list_domain"]:
            mail = collect_mail(project["list_domain"], CORPUS / project["id"] / "mail-threads")
        stats = write_project(project, cases, mail)
        index.append({"bench": project["bench"], "project": project["id"], "repo": project["repo"], "stats": stats, "why": project["why"]})
    index_path = BENCH / "docs" / "data" / "multi-bench-latest.json"
    index_path.write_text(json.dumps({
        "schema_version": 1,
        "generated_at": now_iso(),
        "window": WINDOW,
        "benches": [
            {"bench": 1, "project": "airflow", "repo": "apache/airflow", "artifact": "docs/data/e2e-proof-latest.json"},
            *index,
        ],
    }, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: {exc}", flush=True)
        raise SystemExit(1)
