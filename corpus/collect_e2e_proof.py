#!/usr/bin/env python3
"""Stratified Airflow PR sample for an end-to-end AIV proof run.

Window: 2025-10-22 .. 2026-10-22.

Each month contributes:
  - confirmed Generated-by disclosures (Claude, Codex, Copilot, Gemini, ChatGPT)
  - merged controls with the template still unfilled
  - closed-unmerged controls with the template still unfilled
  - pull requests whose text mentions an AI edit marker

A case is objective slop only when the patch itself contains the bench's
hard markers. A filled Generated-by line is disclosure, not a fail label.
Merged controls are the false-positive check. Closed-unmerged controls are
a population sample, not ground truth.

Sampling is the latest N created in each month (one search page). It is a
sample, not a census of the ~3.5k Claude disclosures in this window.
"""

from __future__ import annotations

import datetime as dt
import json
import subprocess
import time
import urllib.parse
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent / "e2e-proof"
PR_DIR = ROOT / "prs"
CASES_PATH = ROOT / "cases.json"
MANIFEST_PATH = ROOT / "manifest.json"
SUMMARY_PATH = Path(__file__).resolve().parents[1] / "docs" / "data" / "e2e-proof-latest.json"
REPO = "apache/airflow"
WINDOW = "2025-10-22..2026-10-22"

MARKER_RULES: list[tuple[str, Any]] = [
    ("merge_conflict", __import__("re").compile(r"(?m)^(<<<<<<<|=======|>>>>>>>)\s")),
    ("ai_search_replace", __import__("re").compile(r"<<<<<<< SEARCH|>>>>>>> REPLACE")),
    (
        "ai_elision",
        __import__("re").compile(
            r"(?im)(\.\.\.\s*(existing|rest of|remaining)\b[^\n]*\b(code|implementation|unchanged)"
            r"|\b(rest|remainder) of (the )?(code|file|implementation)\b[^\n]*\b(unchanged|omitted)"
            r"|YOUR_CODE_HERE|INSERT_YOUR_CODE)"
        ),
    ),
    (
        "ai_assistant_chatter",
        __import__("re").compile(
            r"(?im)(as an ai language model|here'?s the (updated|complete|fixed|full) (code|implementation))"
        ),
    ),
    (
        "ai_attribution",
        __import__("re").compile(
            r"(?i)generated by (chatgpt|claude|copilot|gemini|ai)|as an ai language model"
        ),
    ),
]

import re

DISCLOSURE_CHECKBOX = re.compile(
    r"(?im)^\s*(?:[-*]\s*)?\[\s*[xX]\s*\].{0,120}(chatgpt|claude|codex|copilot|gemini|generative ai|yes \(please specify)"
)
GENERATED_BY_LINE = re.compile(r"(?im)^Generated-by:\s*(.+)$")

# Latest-N per month. Disclosure phrases are the filled trailer, not the template placeholder.
DISCLOSURE_QUERIES: list[tuple[str, str, int]] = [
    ("claude", '"Generated-by: Claude"', 15),
    ("codex", '"Generated-by: Codex"', 8),
    ("copilot", '"Generated-by: Copilot"', 6),
    ("gemini", '"Generated-by: Gemini"', 4),
    ("chatgpt", '"Generated-by: ChatGPT"', 4),
]
CONTROL_MERGED = 12
CONTROL_UNMERGED = 12
MARKER_QUERY = '"<<<<<<< SEARCH"'
MARKER_CAP = 8
MAX_ADDITIONS = 4000
MAX_FILES = 50
PATCH_CAP = 120_000


def now_iso() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat()


def months() -> list[tuple[dt.date, dt.date]]:
    ranges = []
    cursor = dt.date(2025, 10, 22)
    last = dt.date(2026, 10, 22)
    while cursor <= last:
        nxt = dt.date(cursor.year + 1, 1, 1) if cursor.month == 12 else dt.date(cursor.year, cursor.month + 1, 1)
        end = min(last, nxt - dt.timedelta(days=1))
        ranges.append((cursor, end))
        cursor = end + dt.timedelta(days=1)
    return ranges


def _gh(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")


def _limited(proc: subprocess.CompletedProcess[str]) -> bool:
    err = ((proc.stderr or "") + (proc.stdout or "")).lower()
    return "rate limit" in err or "http 403" in err or "http 429" in err


def gh_json(path: str) -> Any:
    proc = _gh(["gh", "api", path])
    if proc.returncode != 0 and _limited(proc):
        print("  rate limit, waiting 60s", flush=True)
        time.sleep(60)
        proc = _gh(["gh", "api", path])
    if proc.returncode != 0:
        raise RuntimeError((proc.stderr or proc.stdout)[:400])
    return json.loads(proc.stdout) if proc.stdout.strip() else None


def gh_search(query: str, per_page: int) -> dict[str, Any]:
    time.sleep(2.4)
    cmd = [
        "gh", "api", "-X", "GET", "search/issues",
        "-f", f"q={query}",
        "-F", f"per_page={per_page}",
        "-F", "page=1",
        "-F", "sort=created",
        "-f", "order=desc",
    ]
    proc = _gh(cmd)
    if proc.returncode != 0 and _limited(proc):
        time.sleep(60)
        proc = _gh(cmd)
    if proc.returncode != 0:
        raise RuntimeError(f"search failed: {(proc.stderr or proc.stdout)[:400]}")
    data = json.loads(proc.stdout) if proc.stdout.strip() else {}
    if int(data.get("total_count") or 0) == 0:
        time.sleep(2.4)
        proc = _gh(cmd)
        if proc.returncode == 0 and proc.stdout.strip():
            data = json.loads(proc.stdout)
    return data


def true_disclosure(body: str) -> dict[str, Any]:
    signals: list[str] = []
    tool = None
    if DISCLOSURE_CHECKBOX.search(body or ""):
        signals.append("checkbox_yes")
    match = GENERATED_BY_LINE.search(body or "")
    val = (match.group(1) if match else "").strip()
    placeholder = (not val) or val.startswith("[Tool Name]") or val.lower().startswith("following")
    if val and not placeholder:
        signals.append("generated_by_filled")
        tool = val.split(" following ", 1)[0].strip()[:80]
    elif val and re.search(r"(?i)chatgpt|claude|codex|copilot|gemini", val):
        signals.append("generated_by_filled")
        tool = val[:80]
    return {
        "signals": signals,
        "disclosed": "checkbox_yes" in signals or "generated_by_filled" in signals,
        "generated_by": tool,
    }


def content_from_patch(patch: str | None) -> str:
    if not patch:
        return ""
    lines = []
    for line in patch.splitlines():
        if line.startswith(("+++", "---", "@@", "-", "\\")):
            continue
        if line.startswith("+"):
            lines.append(line[1:])
        else:
            lines.append(line[1:] if line.startswith(" ") else line)
    return "\n".join(lines)


def scan_markers(text: str) -> list[str]:
    return [name for name, pattern in MARKER_RULES if text and pattern.search(text)]


def fetch_pr(number: int) -> dict[str, Any]:
    dest = PR_DIR / f"{number}.json"
    if dest.is_file():
        return json.loads(dest.read_text(encoding="utf-8"))
    pr = gh_json(f"repos/{REPO}/pulls/{number}")
    additions = int(pr.get("additions") or 0)
    changed = int(pr.get("changed_files") or 0)
    too_big = additions > MAX_ADDITIONS or changed > MAX_FILES
    files: list[dict[str, Any]] = []
    markers: list[str] = []
    if not too_big:
        page = 1
        while page <= 2:
            batch = gh_json(
                f"repos/{REPO}/pulls/{number}/files?"
                + urllib.parse.urlencode({"per_page": "100", "page": str(page)})
            ) or []
            for f in batch:
                patch = f.get("patch") or ""
                truncated = len(patch) > PATCH_CAP
                if truncated:
                    patch = patch[:PATCH_CAP]
                files.append({
                    "filename": f.get("filename"),
                    "status": f.get("status"),
                    "additions": f.get("additions"),
                    "deletions": f.get("deletions"),
                    "patch": patch or None,
                    "patch_truncated": truncated,
                    "patch_omitted": f.get("patch") is None and f.get("status") != "removed",
                })
            if len(batch) < 100:
                break
            page += 1
        blob = "\n".join(content_from_patch(f.get("patch")) for f in files)
        markers = scan_markers(blob)
    body = pr.get("body") or ""
    record = {
        "number": pr["number"],
        "url": pr.get("html_url"),
        "title": pr.get("title"),
        "state": pr.get("state"),
        "merged": bool(pr.get("merged")),
        "draft": bool(pr.get("draft")),
        "user": (pr.get("user") or {}).get("login"),
        "created_at": pr.get("created_at"),
        "closed_at": pr.get("closed_at"),
        "merged_at": pr.get("merged_at"),
        "base_sha": (pr.get("base") or {}).get("sha"),
        "head_sha": (pr.get("head") or {}).get("sha"),
        "additions": additions,
        "deletions": pr.get("deletions"),
        "changed_files": changed,
        "too_big": too_big,
        "body": body[:80_000],
        "disclosure": true_disclosure(body),
        "markers_in_patch": markers,
        "files": files,
    }
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(record, ensure_ascii=False), encoding="utf-8")
    return record


def label_for(pr: dict[str, Any], cohort: str) -> dict[str, Any]:
    markers = pr.get("markers_in_patch") or []
    disclosed = (pr.get("disclosure") or {}).get("disclosed")
    if markers:
        return {
            "class": "objective_slop",
            "expect_hard_fail": True,
            "expect_advisory": None,
            "rationale": "Patch contains bench hard markers: " + ", ".join(markers),
        }
    if cohort == "merged_control":
        return {
            "class": "merged_control",
            "expect_hard_fail": False,
            "expect_advisory": False,
            "rationale": "Merged, template disclosure unfilled, no hard markers. A hard fail is a false positive.",
        }
    if cohort == "closed_unmerged_sample":
        return {
            "class": "closed_unmerged_sample",
            "expect_hard_fail": False,
            "expect_advisory": None,
            "rationale": "Closed unmerged without disclosure or hard markers. Population sample, not slop ground truth.",
        }
    return {
        "class": "ai_disclosed",
        "expect_hard_fail": False,
        "expect_advisory": None,
        "rationale": (
            "Confirmed AI disclosure ("
            + ", ".join((pr.get("disclosure") or {}).get("signals") or [])
            + "). Disclosure is not a fail label."
        ),
    }


def make_case(pr: dict[str, Any], cohort: str, month: str) -> dict[str, Any]:
    label = label_for(pr, cohort)
    expected = {
        "objective_slop": "ai_slop_positive",
        "merged_control": "merged_real",
        "closed_unmerged_sample": "closed_unmerged_real",
        "ai_disclosed": "ai_disclosed_real",
    }[label["class"]]
    return {
        "id": f"proof-pr-{pr['number']}",
        "source": "github",
        "repo": REPO,
        "pr": pr["number"],
        "url": pr["url"],
        "title": pr["title"],
        "state": pr["state"],
        "merged": pr["merged"],
        "cohort": cohort,
        "month": month,
        "runnable": not pr.get("too_big"),
        "head_sha": pr.get("head_sha"),
        "base_sha": pr.get("base_sha"),
        "additions": pr.get("additions"),
        "changed_files": pr.get("changed_files"),
        "disclosure": pr.get("disclosure"),
        "discovery": {
            "markers_in_patch": pr.get("markers_in_patch") or [],
            "scanned_at": now_iso(),
        },
        "label": label,
        "expected": expected,
        "patch_file": f"corpus/e2e-proof/prs/{pr['number']}.json",
        "notes": label["rationale"],
    }


def search_month(start: dt.date, end: dt.date, extra: str, per_page: int) -> tuple[int, list[dict[str, Any]]]:
    query = f"repo:{REPO} is:pr created:{start.isoformat()}..{end.isoformat()} {extra}".strip()
    print(f"search {start}..{end} {extra}", flush=True)
    data = gh_search(query, per_page)
    total = int(data.get("total_count") or 0)
    items = list(data.get("items") or [])
    print(f"  total {total}, page {len(items)}", flush=True)
    return total, items


def take_cases(
    items: list[dict[str, Any]],
    quota: int,
    month: str,
    cohort: str,
    seen: dict[int, dict[str, Any]],
    *,
    require_disclosure: bool,
    marker_only: bool = False,
) -> list[dict[str, Any]]:
    kept: list[dict[str, Any]] = []
    for item in items:
        if len(kept) >= quota:
            break
        number = int(item["number"])
        if number in seen:
            continue
        body = item.get("body") or ""
        disclosed = true_disclosure(body)["disclosed"]
        if not marker_only:
            if require_disclosure and not disclosed:
                continue
            if not require_disclosure and disclosed:
                continue
        try:
            pr = fetch_pr(number)
        except Exception as exc:  # noqa: BLE001
            print(f"    skip #{number}: {exc}", flush=True)
            continue
        if pr.get("too_big"):
            print(f"    skip #{number} size +{pr['additions']} files {pr['changed_files']}", flush=True)
            continue
        if marker_only and not pr.get("markers_in_patch"):
            continue
        if not marker_only and require_disclosure and not pr["disclosure"]["disclosed"]:
            continue
        if not marker_only and not require_disclosure and pr["disclosure"]["disclosed"]:
            continue
        case = make_case(pr, cohort, month)
        # Marker hits outrank the sampling cohort.
        if case["label"]["class"] == "objective_slop":
            case["cohort"] = "objective_slop"
        seen[number] = case
        kept.append(case)
        print(f"    #{number} {case['label']['class']} {case['cohort']}", flush=True)
    return kept


def main() -> int:
    ROOT.mkdir(parents=True, exist_ok=True)
    seen: dict[int, dict[str, Any]] = {}
    population: dict[str, int] = {}
    for start, end in months():
        month = f"{start.year:04d}-{start.month:02d}"
        for cohort, phrase, quota in DISCLOSURE_QUERIES:
            total, items = search_month(start, end, phrase, max(quota * 2, 20))
            population[f"{month}:{cohort}"] = total
            take_cases(items, quota, month, cohort, seen, require_disclosure=True)
        total, items = search_month(start, end, "is:merged", CONTROL_MERGED * 3)
        population[f"{month}:merged"] = total
        take_cases(items, CONTROL_MERGED, month, "merged_control", seen, require_disclosure=False)
        total, items = search_month(start, end, "is:closed is:unmerged", CONTROL_UNMERGED * 3)
        population[f"{month}:closed_unmerged"] = total
        take_cases(items, CONTROL_UNMERGED, month, "closed_unmerged_sample", seen, require_disclosure=False)
        total, items = search_month(start, end, MARKER_QUERY, 20)
        population[f"{month}:search_marker"] = total
        take_cases(
            items, MARKER_CAP, month, "marker_search", seen,
            require_disclosure=False, marker_only=True,
        )

    cases = [seen[n] for n in sorted(seen)]
    by_class: dict[str, int] = {}
    by_cohort: dict[str, int] = {}
    for case in cases:
        by_class[case["label"]["class"]] = by_class.get(case["label"]["class"], 0) + 1
        by_cohort[case["cohort"]] = by_cohort.get(case["cohort"], 0) + 1
    corpus = {
        "schema_version": 2,
        "purpose": "Large real-Airflow sample for an end-to-end AIV run",
        "repo_upstream": f"https://github.com/{REPO}",
        "window": WINDOW,
        "generated_at": now_iso(),
        "sampling": (
            "Latest N created per month, one search page, after dropping oversized diffs. "
            "Disclosure queries match a filled Generated-by trailer. "
            "Not a census."
        ),
        "methodology": {
            "objective_slop": "Patch text matched AIV hard markers. expect_hard_fail true.",
            "ai_disclosed": "Checkbox yes or Generated-by filled with a real tool. expect_hard_fail false.",
            "merged_control": "Merged, disclosure unfilled, no hard markers. Hard fail = false positive.",
            "closed_unmerged_sample": "Closed unmerged without disclosure or markers. Not slop ground truth.",
            "not_claimed": [
                "Filled disclosure does not mean the PR should fail.",
                "This sample is not the fraction of all Airflow PRs that are AI-authored.",
                "Closed-unmerged is not AI slop.",
                "Search totals for Generated-by include only the sampled months' reported totals, not a scored census.",
            ],
        },
        "population_search_totals": population,
        "stats": {
            "cases": len(cases),
            "runnable": sum(1 for c in cases if c["runnable"]),
            "by_class": by_class,
            "by_cohort": by_cohort,
            "objective_slop": by_class.get("objective_slop", 0),
            "ai_disclosed": by_class.get("ai_disclosed", 0),
            "merged_control": by_class.get("merged_control", 0),
            "closed_unmerged_sample": by_class.get("closed_unmerged_sample", 0),
        },
        "cases": cases,
    }
    CASES_PATH.write_text(json.dumps(corpus, ensure_ascii=False, indent=2), encoding="utf-8")
    manifest = {
        "schema_version": 1,
        "generated_at": corpus["generated_at"],
        "window": WINDOW,
        "stats": corpus["stats"],
        "sampling": corpus["sampling"],
        "not_claimed": corpus["methodology"]["not_claimed"],
        "artifacts": {
            "cases": "corpus/e2e-proof/cases.json",
            "patches": "corpus/e2e-proof/prs/<number>.json",
        },
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    summary = {
        "schema_version": 1,
        "generated_at": corpus["generated_at"],
        "window": WINDOW,
        "stats": corpus["stats"],
        "sampling": corpus["sampling"],
        "not_claimed": corpus["methodology"]["not_claimed"],
        "cases": [
            {
                "id": c["id"],
                "pr": c["pr"],
                "url": c["url"],
                "title": c["title"],
                "state": c["state"],
                "merged": c["merged"],
                "cohort": c["cohort"],
                "month": c["month"],
                "label": c["label"]["class"],
                "expect_hard_fail": c["label"]["expect_hard_fail"],
                "markers_in_patch": c["discovery"]["markers_in_patch"],
                "generated_by": (c.get("disclosure") or {}).get("generated_by"),
                "additions": c["additions"],
                "changed_files": c["changed_files"],
            }
            for c in cases
        ],
    }
    SUMMARY_PATH.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_PATH.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(corpus["stats"], indent=2), flush=True)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: {exc}", flush=True)
        raise SystemExit(1)
